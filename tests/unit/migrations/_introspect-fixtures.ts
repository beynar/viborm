/**
 * Shared estates for `introspectSchema` round trips.
 *
 * `RICH_POSTGRES_SQL` is a database written by hand, in plain PostgreSQL, the
 * way an existing application's schema is: a named enum, native types (varchar,
 * char, numeric, real, json and jsonb, bytea, arrays, timestamp with and without
 * time zone), several foreign keys to one table, a self relation, a one-to-one,
 * a many-to-many join table, unique and compound keys, defaults and nullable
 * columns. It is written within what a document can state exactly, so the round
 * trip must plan NOTHING; `RICH_SKIPPED_SQL` adds what it cannot.
 *
 * `codedSchema()` is the other direction: a TypeScript schema VibORM pushes
 * itself, which the document must find again.
 */

