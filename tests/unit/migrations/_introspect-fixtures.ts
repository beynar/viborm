/** A TypeScript schema VibORM pushes itself. */
export function codedSchema() {
  const member = s
    .model({
      id: s.string().id().uuid(),
      email: s.string().unique(),
      handle: s.string({ db: "pg", type: "varchar(40)" }).nullable(),
      role: s.enum(["owner", "member"]).name("member_role").default("member"),
      plan: s.enum(["free", "pro"]).default("free"),
      score: s.number().default(1.5),
      credits: s.int().default(10),
      balance: s.decimal({ precision: 10, scale: 2 }).default("0.00"),
      active: s.boolean().default(true),
      settings: s.json().nullable(),
      createdAt: s.dateTime().now(),
      seenAt: s.dateTime().nullable(),
      mentorId: s.string().uuid().nullable(),
      mentor: s
        .toOne(() => member)
        .name("mentorship")
        .fields("mentorId")
        .references("id")
        .onDelete("setNull"),
      mentees: s.toMany(() => member).name("mentorship"),
      authored: s.toMany(() => article).name("authorship"),
      edited: s.toMany(() => article).name("editing"),
    })
    .map("members");
  const article = s
    .model({
      id: s.int().id().increment(),
      authorId: s.string().uuid(),
      editorId: s.string().uuid().nullable(),
      title: s.string(),
      tags: s.string().array(),
      author: s
        .toOne(() => member)
        .name("authorship")
        .fields("authorId")
        .references("id")
        .onDelete("cascade"),
      editor: s
        .toOne(() => member)
        .name("editing")
        .fields("editorId")
        .references("id"),
      topics: s.toMany(() => topic),
    })
    .unique(["authorId", "title"])
    .index(["title"]);
  const topic = s.model({
    id: s.int().id(),
    label: s.string().unique(),
    articles: s.toMany(() => article),
  });
  return { member, article, topic };
}

/** The models, relations and key facts of a document, for comparison. */
export function documentShape(document: ReturnType<typeof serializeSchema>) {
  return Object.fromEntries(
    Object.entries(document.models).map(([key, model]) => [
      model.table ?? key,
      Object.fromEntries(
        Object.entries(model.fields).map(([field, value]) => [
          field,
          value.type,
        ])
      ),
    ])
  );
}

/**
 * The main contract: introspect, parse the document, push it against the same
 * database. The plan must be empty — no operation, no drift warning.
 */
export async function expectEmptyRoundTrip(
  driver: AnyDriver,
  tables: readonly string[]
) {
  const result = await introspectSchema({ driver, tables });
  expect(result.warnings.filter((warning) => warning.kind === "drift")).toEqual(
    []
  );
  const schema = parseSchema(result.document, { validate: true });
  const client = createClient({ schema, driver });
  const migrations = createMigrationClient(client, { tables: [...tables] });
  const preview = await migrations.push({ dryRun: true });
  expect(preview.operations).toEqual([]);
  expect(preview.statements).toEqual([]);
  expect(preview.outcome).toBe("noop");
  // The document is already canonical.
  expect(serializeSchema(parseSchema(result.document))).toEqual(
    result.document
  );
  return { result, client };
}
